export function getHolidaysForLanguage(lang: TargetLanguage = "ja"): HolidayItem[] {
  if (lang === "de") return GERMAN_HOLIDAYS;
  if (lang === "es") return SPANISH_HOLIDAYS;
  return JAPANESE_HOLIDAYS;
}

export function getHolidayById(holidayId: string | undefined, lang: TargetLanguage = "ja"): HolidayItem | undefined {
  if (!holidayId || holidayId === "none") return undefined;
  const list = getHolidaysForLanguage(lang);
  return list.find((h) => h.id === holidayId);
}

